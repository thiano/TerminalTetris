namespace TerminalTetris.Enums;

/*
 * Defines the 7 standard tetromino geometric piece configurations.
 * Conforms to the official Tetris Guideline specifications.
 */
public enum tetrominoType
{
    // Straight line piece (Cyan)
    I,

    // Left-facing L piece (Blue)
    J,

    // Right-facing L piece (Orange)
    L,

    // Square 2x2 piece (Yellow)
    O,

    // Right-facing snake piece (Green)
    S,

    // T-junction piece (Magenta)
    T,

    // Left-facing snake piece (Red)
    Z
}